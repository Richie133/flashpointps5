#!/usr/bin/env python3
"""Packs the www/ folder into a C file so the payload is a single ELF.

usage: embed.py <www dir> <output.c>
"""
import os
import sys


def main():
    root, out = sys.argv[1], sys.argv[2]
    files = []
    for dirpath, _, names in os.walk(root):
        for name in sorted(names):
            if name.startswith('.'):
                continue
            full = os.path.join(dirpath, name)
            rel = '/' + os.path.relpath(full, root).replace(os.sep, '/')
            files.append((rel, full))
    files.sort()
    with open(out, 'w') as f:
        f.write('/* generated by tools/embed.py - do not edit */\n')
        f.write('#include <string.h>\n#include "assets.h"\n\n')
        for i, (rel, full) in enumerate(files):
            data = open(full, 'rb').read()
            f.write(f'/* {rel} */\nstatic const unsigned char a{i}[] = {{')
            for j, b in enumerate(data):
                if j % 24 == 0:
                    f.write('\n')
                f.write(f'{b},')
            f.write('0};\n')
        f.write('\nstatic const asset_t k_assets[] = {\n')
        for i, (rel, full) in enumerate(files):
            size = os.path.getsize(full)
            f.write(f'  {{"{rel}", a{i}, {size}}},\n')
        f.write('  {0, 0, 0},\n};\n\n')
        f.write('const asset_t *asset_find(const char *path) {\n'
                '  for (const asset_t *a = k_assets; a->path; a++) {\n'
                '    if (!strcmp(a->path, path)) return a;\n'
                '  }\n'
                '  return 0;\n'
                '}\n')


if __name__ == '__main__':
    main()
